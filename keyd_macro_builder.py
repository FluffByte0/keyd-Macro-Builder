from __future__ import annotations

import argparse
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import TypeAlias


@dataclass(frozen=True)
class Text:
    value: str

@dataclass(frozen=True)
class Delay:
    milliseconds: int

@dataclass(frozen=True)
class Key:
    """A key name or chord understood by keyd."""

    value: str

Step: TypeAlias = Text | Delay | Key
# Example; "<key>": [Text(""), Delay(), Key("")],

# Keyd key reference:
# - Modifiers: C = Ctrl, M = Windows/Meta/Super, A = Alt, S = Shift, G = AltGr.
# - Use hyphens for modifier chords: Key("C-M-r") sends Ctrl+Windows+R.
# - Use plus signs for ordinary keys pressed together: Key("a+b").
# - To tap only the Windows key, use "leftmeta" or "rightmeta".
# - Common key names include enter, tab, esc, space, left, right, up, down, f1-f12 and a-z.
# - You can also add hardware-control keys, some examples (not all) are in README.txt.
# - Modifier keys should be capitalized while non-modifier keys should be lowercase.

# Add, remove, or edit automations here. Valid numpad names include kp0-kp9, kpplus, kpminus, kpasterisk, kpslash, kpenter, and kpdot. Or bind any other key.
AUTOMATIONS: dict[str, list[Step]] = {
    # Key:
    "<key>": [Text(""), Delay(), Key("")],
}

PROJECT_DIRECTORY = Path(__file__).resolve().parent
OUTPUT_PATH = PROJECT_DIRECTORY / "keyd-typing.conf"
SYSTEM_CONFIG_PATH = Path("/etc/keyd/default.conf")


def text_tokens(value: str) -> list[str]:
    """Turn plain text into unambiguous keyd macro tokens."""
    tokens: list[str] = []
    for character in value:
        if character == " ":
            tokens.append("space")
        elif character == "\n":
            tokens.append("enter")
        elif character == "\t":
            tokens.append("tab")
        else:
            tokens.append(character)
    return tokens


def compile_steps(steps: list[Step]) -> str:
    tokens: list[str] = []
    for step in steps:
        if isinstance(step, Text):
            tokens.extend(text_tokens(step.value))
        elif isinstance(step, Delay):
            if not isinstance(step.milliseconds, int) or isinstance(step.milliseconds, bool):
                raise ValueError(
                    "Delay milliseconds must be an integer."
                )
            if not 0 < step.milliseconds <= 5001:
                raise ValueError("Each delay must be between 1 and 5000 milliseconds.")
            tokens.append(f"{step.milliseconds}ms")
        elif isinstance(step, Key):
            tokens.append(step.value)
        else:
            raise TypeError(f"Unsupported step: {step!r}")
    if not tokens:
        raise ValueError("An automation needs at least one step.")
    return f"macro({' '.join(tokens)})"


def build_config() -> str:
    lines = [
        "# Generated by keyd_macro_builder.py. It is crucial to edit the Python file, not this one.",
        "",
        "[ids]",
        "*",
        "",
        "[main]",
    ]
    for trigger, steps in AUTOMATIONS.items():
        lines.append(f"{trigger} = {compile_steps(steps)}")
    return "\n".join(lines) + "\n"


def write_config() -> None:
    OUTPUT_PATH.write_text(build_config(), encoding="utf-8")
    print(f"Generated {OUTPUT_PATH}")

'''Allows the terminal to update the macro config.'''
def install_config() -> None:
    write_config()
    subprocess.run(
        ["sudo", "install", "-Dm644", str(OUTPUT_PATH), str(SYSTEM_CONFIG_PATH)], # Copies file keyd-typing.conf to /etc/keyd/default.conf.
        check=True,
    )
    subprocess.run(["sudo", "systemctl", "enable", "--now", "keyd.service"], check=True) # Runs the keyd service.
    subprocess.run(["sudo", "keyd", "reload"], check=True) # Required for changes to update in /etc/keyd/default.conf.
    print("Installed and reloaded keyd macros.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--install",
        action="store_true",
        help="install the generated config and reload keyd (asks for your sudo password)",
    )
    args = parser.parse_args()

    try:
        if args.install:
            install_config()
        else:
            write_config()
            print("Review it, then run this script again with --install.")
    except (OSError, subprocess.CalledProcessError, ValueError) as error:
        sys.exit(f"Error: {error}")


if __name__ == "__main__":
    main()
